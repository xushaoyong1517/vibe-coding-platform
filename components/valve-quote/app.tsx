function matchDrawing(item: QuoteItem, drawings: DrawingTemplate[]): DrawingTemplate | null {
  return (
    drawings.find(d =>
      d.valve_type === item.类型 &&
      d.pressure === item.压力 &&
      d.actuator === item.驱动 &&
      item.DN >= d.dn_min && item.DN <= d.dn_max
    ) ??
    drawings.find(d =>
      d.valve_type === item.类型 &&
      d.pressure === item.压力 &&
      item.DN >= d.dn_min && item.DN <= d.dn_max
    ) ??
    null
  )
}

