function deriveProductJianHao(p: ValveProduct): string {
  if (p.U6 === 'Y2') {
    if (['L','R'].includes(p.U8)) return '16#'
    if (['P','L1'].includes(p.U8)) return '15#'
    return '5#'
  }
  if (p.U6 === 'W') {
    if (['P','L1'].includes(p.U8)) return (p.U14 === '04'||p.U14==='06') ? '10#' : '2#'
    if (['L','R'].includes(p.U8)) return '10#'
    if (p.U8 === 'C2') return '2#'
    return '1#'
  }
  if (p.U6 === 'H') return '1#'
  return '1#'
}

